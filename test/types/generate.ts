#!/usr/bin/env bun
/**
 * Writes test/types/wire.ts from the encoders (#132). Run after an intended wire change:
 *
 *   bun test/types/generate.ts && bun run typecheck && bun test test/unit/wire.test.ts
 *
 * Each golden is a literal that `satisfies` the official SDK type for that shape, so the type
 * check fails when plugboard's output and the SDK's idea of the wire disagree.
 */
import { scenarios } from "./scenarios.js"

type Scenarios = Awaited<ReturnType<typeof scenarios>>

/**
 * Golden name, its value in the scenarios, the SDK type, and the known exact-type gaps: required
 * SDK fields plugboard does not send (an empty list means the golden is exactly the SDK type).
 */
const GOLDENS: ReadonlyArray<readonly [string, (s: Scenarios) => unknown, string, string?]> = [
  ["chatCompletion", (s) => s.chat.completion, "OpenAI.Chat.Completions.ChatCompletion"],
  ["chatCompletionChunks", (s) => s.chat.chunks, "OpenAI.Chat.Completions.ChatCompletionChunk[]"],
  ["chatError", (s) => s.chat.error, "{ error: OpenAI.ErrorObject }"],
  ["chatModelList", (s) => s.chat.models, "{ object: \"list\"; data: Array<OpenAI.Models.Model & { plugboard: unknown; context_length?: number; max_output_tokens?: number; pricing?: { prompt: string; completion: string; input_cache_read?: string; input_cache_write?: string } }> }"],
  // `store` and `name` (on function_call_arguments.done) are in OpenAI's API reference but not in the SDK's types.
  ["responsesResponse", (s) => s.responses.response, "OpenAI.Responses.Response & { store: boolean }"],
  [
    "responsesEvents",
    (s) => s.responses.events,
    "Array<(OpenAI.Responses.ResponseStreamEvent & { response?: { store: boolean } }) | (OpenAI.Responses.ResponseFunctionCallArgumentsDoneEvent & { name: string })>",
  ],
  ["completion", (s) => s.completions.completion, "OpenAI.Completions.Completion"],
  ["completionChunks", (s) => s.completions.chunks, "OpenAI.Completions.Completion[]"],
  ["anthropicMessage", (s) => s.messages.message, "Anthropic.Message"],
  ["anthropicEvents", (s) => s.messages.events, "Array<Anthropic.RawMessageStreamEvent | { type: \"ping\" }>"],
  ["anthropicError", (s) => s.messages.error, "Anthropic.ErrorResponse"],
  ["geminiResponse", (s) => s.gemini.response, "GeminiResponse"],
  ["geminiChunks", (s) => s.gemini.chunks, "GeminiResponse[]"],
]

/** Exact-type gaps, by golden: the reason printed above its `@ts-expect-error`. Filled from what `tsc` reports. */
const GAPS: Readonly<Record<string, string>> = {
  responsesResponse: "plugboard omits output_text (the SDK computes it client-side), access_programs and usage.input_tokens_details.cache_write_tokens",
  responsesEvents: "the response objects in created/in_progress/completed omit output_text, access_programs and cache_write_tokens (see responsesResponse)",
  completionChunks: "stream chunks carry finish_reason null until the last; the SDK types chunks as Completion, whose finish_reason is never null",
  anthropicMessage: "plugboard omits nullable fields Anthropic always sends: container, diagnostics, stop_details, text citations, usage cache_creation, inference_geo, output_tokens_details, server_tool_use, service_tier",
  anthropicEvents: "message_start and message_delta omit the same nullable fields as anthropicMessage (container, stop_details, usage details)",
  anthropicError: "request_id is sent as the request-id header, not in the body",
}

const s = await scenarios()
const lines = [
  "// Generated by test/types/generate.ts from the encoders. Do not edit; regenerate after an intended wire change.",
  "// Each golden must satisfy the official SDK type of its shape (#132); test/unit/wire.test.ts checks the encoders still produce it.",
  'import type Anthropic from "@anthropic-ai/sdk"',
  'import type { GenerateContentResponse } from "@google/genai"',
  'import type OpenAI from "openai"',
  'import { exact, type Unenum, type Wire } from "./sdk.js"',
  "",
  "/** The data fields of the SDK class (its getters such as `text` are computed client-side, never on the wire). */",
  'type GeminiResponse = Unenum<Pick<GenerateContentResponse, "candidates" | "modelVersion" | "responseId" | "usageMetadata" | "promptFeedback">>',
  "",
]
for (const [name, pick, type] of GOLDENS) lines.push(`export const ${name} = ${JSON.stringify(pick(s), null, 2)} satisfies Wire<${type}>`, "")
lines.push("// Exact SDK types: a known gap is a `@ts-expect-error` that must go once the gap is closed.")
for (const [name, , type] of GOLDENS) {
  if (GAPS[name]) lines.push(`// @ts-expect-error ${GAPS[name]}`)
  lines.push(`exact<${type}>(${name})`)
}
lines.push("")
await Bun.write(new URL("./wire.ts", import.meta.url), lines.join("\n"))
console.log(`wrote ${GOLDENS.length} goldens to test/types/wire.ts`)
